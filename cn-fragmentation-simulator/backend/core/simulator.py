"""
Unified IPv4 Simulation Pipeline for Intelligent IPv4 Fragmentation & Network Failure Simulator.

Orchestrates the complete lifecycle of an IPv4 packet:
1. Fragmentation: Splits original datagram into standard IPv4 fragments based on link MTU,
   or prevents fragmentation if the DF (Don't Fragment) flag is set on an oversized datagram.
2. Transmission: Simulates transmission over an unreliable network (reordering, loss, duplication, delay, corruption).
3. Reassembly: Logically reassembles delivered fragments and verifies data integrity.
4. Result: Aggregates end-to-end pipeline metrics into a unified SimulationResult.
"""

from dataclasses import dataclass, field
from typing import List, Optional
from .models import Fragment
from .fragmenter import fragment_packet
from .transmitter import TransmissionConfig, TransmissionEvent, TransmissionResult, simulate_transmission
from .reassembler import ReassemblyResult, reassemble_fragments


@dataclass
class SimulationConfig:
    """
    Configuration for an end-to-end IPv4 packet fragmentation, transmission, and reassembly simulation.

    Attributes:
        payload_size (int): Size of the unfragmented datagram payload in bytes.
        mtu (int): Maximum Transmission Unit of the network link in bytes.
        identification (int): 16-bit IPv4 Identification value (0 to 65535).
        header_size (int): Size of the IPv4 header in bytes (default: 20 bytes).
        df (bool): IPv4 Don't Fragment flag (default: False).
        transmission (TransmissionConfig): Network failure and latency conditions for transmission.
    """

    payload_size: int
    mtu: int
    identification: int
    header_size: int = 20
    df: bool = False
    transmission: TransmissionConfig = field(default_factory=TransmissionConfig)

    @property
    def transmission_config(self) -> TransmissionConfig:
        """Alias for transmission configuration."""
        return self.transmission


@dataclass
class SimulationResult:
    """
    Unified end-to-end simulation result.

    Attributes:
        payload_size (int): Original packet payload size in bytes.
        mtu (int): Link MTU in bytes.
        identification (int): 16-bit IPv4 Identification value.
        header_size (int): IPv4 header size in bytes.
        generated_fragments (List[Fragment]): Ordered fragments generated by fragmentation engine.
        transmission_result (TransmissionResult): Results and event timeline from transmission simulation.
        reassembly_result (ReassemblyResult): Layout analysis and outcome from reassembly engine.
        success (bool): Overall simulation success status (True if packet was fully reassembled).
        df (bool): Configured IPv4 Don't Fragment flag value.
        fragmentation_prevented (bool): True if datagram exceeded MTU but could not be fragmented due to DF=1.
        status (str): Simulation lifecycle status ("success", "reassembly_failed", "fragmentation_prevented").
        reason (Optional[str]): Informational detail on the final simulation verdict or failure cause.
    """

    payload_size: int
    mtu: int
    identification: int
    header_size: int
    generated_fragments: List[Fragment]
    transmission_result: TransmissionResult
    reassembly_result: ReassemblyResult
    success: bool
    df: bool = False
    fragmentation_prevented: bool = False
    status: str = "success"
    reason: Optional[str] = None

    @property
    def fragment_count(self) -> int:
        """Number of fragments generated during fragmentation."""
        return len(self.generated_fragments)


def simulate_packet(config: SimulationConfig) -> SimulationResult:
    """
    Executes the complete unified IPv4 packet simulation pipeline:
    Fragmentation -> Transmission Simulation -> Reassembly.

    RFC 791 Decision Rules:
    1. Packet size (header + payload) <= MTU:
       - No fragmentation required. 1 datagram representation produced with DF preserved.
    2. Packet size > MTU and DF = 0:
       - Normal RFC 791 fragmentation into 8-byte aligned fragments.
    3. Packet size > MTU and DF = 1:
       - Fragmentation prevented. 0 fragments generated. Simulation status marked prevented.

    Args:
        config (SimulationConfig): Complete simulation parameters.

    Returns:
        SimulationResult: Unified result containing outcomes from all pipeline stages.
    """
    if not isinstance(config, SimulationConfig):
        raise TypeError(f"config must be an instance of SimulationConfig, got {type(config).__name__}")

    packet_size = config.header_size + config.payload_size
    exceeds_mtu = packet_size > config.mtu

    # CASE C: Packet exceeds MTU and DF is set (RFC 791 Don't Fragment Rule)
    if exceeds_mtu and config.df:
        reason_msg = "Fragmentation required, but DF flag is set."

        # Zero generated fragments: fragmentation is blocked
        generated_fragments: List[Fragment] = []

        # Transmission result reflects dropped datagram
        tx_delay = config.transmission.delay_ms if config.transmission else 0
        tx_event = TransmissionEvent(
            sequence_number=1,
            original_fragment_index=-1,
            action="dropped",
            delay_ms=tx_delay,
            detail="Fragmentation required, but DF flag is set; packet dropped (simulation).",
        )
        transmission_result = TransmissionResult(
            delivered_fragments=[],
            events=[tx_event],
            total_input=0,
            delivered_count=0,
            dropped_count=0,
            duplicate_count=0,
            corrupted_count=0,
        )

        # Reassembly result reflects that no fragments were available
        reassembly_result = ReassemblyResult(
            success=False,
            identification=config.identification,
            fragment_count=0,
            payload_size=0,
            missing_ranges=[(0, config.payload_size)] if config.payload_size > 0 else [],
            overlaps=[],
            reason=reason_msg,
            expected_end_offset=config.payload_size if config.payload_size > 0 else None,
        )

        return SimulationResult(
            payload_size=config.payload_size,
            mtu=config.mtu,
            identification=config.identification,
            header_size=config.header_size,
            generated_fragments=generated_fragments,
            transmission_result=transmission_result,
            reassembly_result=reassembly_result,
            success=False,
            df=True,
            fragmentation_prevented=True,
            status="fragmentation_prevented",
            reason=reason_msg,
        )

    # STEP A: Fragmentation (Cases A and B)
    generated_fragments = fragment_packet(
        payload_size=config.payload_size,
        mtu=config.mtu,
        identification=config.identification,
        header_size=config.header_size,
        df=config.df,
    )

    # STEP B: Transmission Simulation
    tx_config = config.transmission if config.transmission is not None else TransmissionConfig()
    transmission_result = simulate_transmission(
        fragments=generated_fragments,
        config=tx_config,
    )

    # STEP C: Reassembly
    reassembly_result = reassemble_fragments(
        fragments=transmission_result.delivered_fragments,
    )

    status_str = "success" if reassembly_result.success else "reassembly_failed"

    # STEP D: Final Unified Result Construction
    return SimulationResult(
        payload_size=config.payload_size,
        mtu=config.mtu,
        identification=config.identification,
        header_size=config.header_size,
        generated_fragments=generated_fragments,
        transmission_result=transmission_result,
        reassembly_result=reassembly_result,
        success=reassembly_result.success,
        df=config.df,
        fragmentation_prevented=False,
        status=status_str,
        reason=reassembly_result.reason,
    )


class PacketSimulator:
    """Unified orchestrator component for IPv4 packet simulation."""

    @staticmethod
    def simulate(config: SimulationConfig) -> SimulationResult:
        """Simulates the entire packet lifecycle from fragmentation through transmission to reassembly."""
        return simulate_packet(config)
